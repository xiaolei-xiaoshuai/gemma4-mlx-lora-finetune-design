    TARGET = 3750
    items, seen = [], set()

    # v1 全部 1500 先入池
    v1 = []
    try:
        for line in open(os.path.join(BASE, "dialogue_1500.jsonl")):
            d = json.loads(line)
            ms = d["messages"]
            v1.append({"turns": [[ms[i]["content"], ms[i+1]["content"]] for i in range(0, len(ms), 2)]})
    except Exception: pass
    for d in v1:
        items.append(d)
    print("v1 载入:", len(v1))

    # 新种子补到 3750（15% 概率加前缀变体；池耗尽后允许重复但每种子 <=5 次）
    pool = list(P)
    uses = {}
    while len(items) < TARGET:
        progress = False
        random.shuffle(pool)
        for seed in pool:
            if len(items) >= TARGET: break
            key = json.dumps(seed, ensure_ascii=False)
            if uses.get(key, 0) >= 5: continue
            uses[key] = uses.get(key, 0) + 1
            if "turns" in seed:
                items.append({"turns": seed["turns"]})
            else:
                u = seed["user"]
                if random.random() < 0.15:
                    u = random.choice(["帮我","请教下","我想知道","麻烦","能不能","聊聊"]) + "，" + u
                items.append({"turns": [[u, seed["assistant"]]]})
            progress = True
        if not progress:
            break

    print("种子池:", len(P), "| 总计:", len(items), "/ 目标", TARGET)
    n_multi = 0
    out = os.path.join(BASE, "dialogue_3750.jsonl")
    with open(out, "w", encoding="utf-8") as f:
        for it in items:
            msgs = []
            for u, a in it["turns"]:
                msgs.append({"role": "user", "content": u})
                msgs.append({"role": "assistant", "content": a})
            if len(msgs) // 2 > 1: n_multi += 1
            f.write(json.dumps({"messages": msgs, "source": "dialogue"}, ensure_ascii=False) + "\n")
    print("写入:", out, "多轮:", n_multi)
